/** 默认主题：海洋蓝 + 浅色。 */
export const DEFAULT_THEME = { family: 'blue' as ThemeFamily, mode: 'light' as ThemeMode };

/** 取某色系某模式的 token 覆盖（配合 ConfigProvider 的 theme.token）。 */
export function getThemeTokens(family: ThemeFamily, mode: ThemeMode): ThemeConfig['token'] {
  return PALETTES[family][mode];
}

/** 某模式是否为暗色（决定 ConfigProvider 用 darkAlgorithm 还是 defaultAlgorithm）。 */
export function isDarkMode(mode: ThemeMode): boolean {
  return mode === 'dark' || mode === 'deepdark';
}

export function isThemeMode(value: string): value is ThemeMode {
  return Object.prototype.hasOwnProperty.call(PALETTES[DEFAULT_THEME.family], value);
}

export function isThemeFamily(value: string): value is ThemeFamily {
  return Object.prototype.hasOwnProperty.call(PALETTES, value);
}
